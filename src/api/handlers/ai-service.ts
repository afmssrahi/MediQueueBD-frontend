/**
 * Build the demo timeline for a patient.
 *
 * @param patientId
 */
function buildDemoTimeline(patientId: string): AiTimelineEntry[] {
  const db = readDb();

  const records = db.records
    .filter((item) => item.patientId === patientId)
    .slice(0, 3);

  if (records.length === 0) return [];
  return records.map((record, index) => ({
    summaryId: `AS${db.counters.summary + index + 1}`,
    documentId: record.id,
    filename: record.documentName ?? `${record.diagnosis}.pdf`,
    uploadedAt: new Date(record.date).toISOString(),
    headline: `${record.diagnosis} — ${record.visitType}`,
    summary:
      `This simulated summary was assembled from the consultation on ${record.date}. ` +
      `The recorded diagnosis was "${record.diagnosis}" and the chief complaint was ` +
      `"${record.chiefComplaint}". It was seen by ${record.doctorName}. ` +
      `This text is generated by a demonstration script, not by a medical model, ` +
      `and it is not a clinical assessment.`,
    originalSummary: "",
    keyFindings: [
      `${record.date} — ${record.diagnosis} (${record.doctorName})`,
      ...(record.vitals.bloodPressure
        ? [`Blood pressure: ${record.vitals.bloodPressure}`]
        : []),
    ],
    medications: db.prescriptions
      .filter((item) => item.patientId === patientId)
      .flatMap((item) =>
        item.items.map(
          (entry) =>
            `${entry.medicine} ${entry.dose} · ${entry.frequency} · ${entry.duration}`,
        ),
      )
      .slice(0, 5),
    allergies: db.allergies
      .filter((item) => item.patientId === patientId)
      .map((item) => `${item.substance} — ${item.reaction}`),
    conditions: db.conditions
      .filter((item) => item.patientId === patientId)
      .map((item) => item.name),
    recommendations: [
      "Confirm the record with the treating clinician before acting on it",
      "Reconcile the medication list at the next consultation",
    ],
    vitals: {
      bloodPressure: record.vitals.bloodPressure,
      temperature: record.vitals.temperature,
      pulse: record.vitals.pulse,
      weight: record.vitals.weight,
      spo2: record.vitals.spo2,
    },
    advice: null,
    followUp: null,
    provider: "demo",
    model: "demo-script",
    confidence: 0.5,
    needsReview: true,
    reviewedBy: null,
    reviewedAt: null,
    citations: DEMO_CITATIONS.slice(0, index === 0 ? 2 : 1).map(
      (citation, position) => ({
        ...citation,
        id: `CIT-${index}-${position}`,
        summaryId: `AS${db.counters.summary + index + 1}`,
      }),
    ),
  }));
}

/**
 * Build the demo history for a patient.
 *
 * @param patientId
 */
function buildDemoHistory(patientId: string): AiHistory {
  const db = readDb();
  const patient = db.users.find((item) => item.id === patientId);
  const timeline = buildDemoTimeline(patientId);

  const summary =
    timeline.length === 0
      ? `${patient?.name ?? "This patient"} has no uploaded documents yet. ` +
        `Once a prescription or medical record is uploaded it will be summarised ` +
        `here and added to this history.`
      : `${patient?.name ?? "This patient"} has ${timeline.length} uploaded ` +
        `document${timeline.length === 1 ? "" : "s"}, summarised into ` +
        `${timeline.length} clinical entr${timeline.length === 1 ? "y" : "ies"}. ` +
        `This simulated history is assembled from the demo database; every entry ` +
        `links back to the record it came from.`;

  return {
    headline:
      timeline.length === 0
        ? "No documents on record"
        : `${timeline.length} entr${timeline.length === 1 ? "y" : "ies"} on record`,
    summary,
    timeline,
    generatedAt: new Date().toISOString(),
  };
}

/**
 * The demo export payload.
 *
 * @param patientId
 */
function buildDemoExport(patientId: string): AiEmrExportBundle {
  const db = readDb();
  const history = buildDemoHistory(patientId);

  const conditions = db.conditions
    .filter((item) => item.patientId === patientId)
    .map((item) => ({
      name: item.name,
      code: item.code,
      status: item.status,
      diagnosedAt: item.diagnosedAt,
      notes: "Identified from an uploaded document by the AI summary service.",
    }));

  const allergies = db.allergies
    .filter((item) => item.patientId === patientId)
    .map((item) => ({
      substance: item.substance,
      reaction: item.reaction,
      severity: item.severity,
      recordedAt: item.recordedAt,
      recordedBy: item.recordedBy,
    }));

  const prescriptions = db.prescriptions
    .filter((item) => item.patientId === patientId)
    .map((item) => ({
      date: item.date,
      doctorName: item.doctorName,
      advice: item.advice,
      notes: "Extracted from an uploaded document.",
      items: item.items.map((entry) => ({
        medicine: entry.medicine,
        dose: entry.dose,
        frequency: entry.frequency,
        duration: entry.duration,
        instructions: null,
      })),
    }));

  const records = db.records
    .filter((item) => item.patientId === patientId)
    .map((item) => ({
      date: item.date,
      visitType: item.visitType,
      chiefComplaint: item.chiefComplaint,
      diagnosis: item.diagnosis,
      notes: item.notes,
      vitals: {
        bloodPressure: item.vitals.bloodPressure,
        temperature: item.vitals.temperature,
        pulse: item.vitals.pulse,
        weight: item.vitals.weight,
        spo2: item.vitals.spo2,
      },
      documentName: item.documentName ?? null,
      documentSize: item.documentSize ?? null,
    }));

  return {
    status: "exported",
    exported: history.timeline.length,
    payload: {
      target: "mediqueue-emr",
      patientId,
      externalPatientId: patientId,
      conditions,
      allergies,
      prescriptions,
      records,
      summary: history.timeline[0]
        ? {
            headline: history.timeline[0].headline,
            text: history.timeline[0].summary,
            keyFindings: history.timeline[0].keyFindings,
            recommendations: history.timeline[0].recommendations,
            advice: history.timeline[0].advice,
            followUp: history.timeline[0].followUp,
            needsReview: history.timeline[0].needsReview,
            reviewedBy: history.timeline[0].reviewedBy,
            reviewedAt: history.timeline[0].reviewedAt,
            provider: history.timeline[0].provider,
            model: history.timeline[0].model,
            confidence: history.timeline[0].confidence,
          }
        : null,
    },
  };
}

/**
 * The AI summary service handlers.
 */
export const aiServiceHandlers: HandlerMap = {
  "POST /ai-service/patients": (request) => {
    const body = bodyOf(request);
    const db = readDb();

    const externalId = String(body.externalId ?? "");
    const name = String(body.name ?? "").trim();

    if (!externalId) {
      return fail(
        "NAME_REQUIRED",
        "The patient must be linked to the medical record.",
        400,
      );
    }

    // The demo service matches on the external id — the same rule the real
    // service uses, so the two behave the same way.
    const existing = db.users.find((item) => item.id === externalId);

    if (!existing) {
      return fail("PATIENT_NOT_FOUND", "No such patient.", 404);
    }

    return ok({
      patient: {
        id: externalId,
        name: name || existing.name,
        age: null,
        sex: existing.gender ?? null,
        externalId,
        createdAt: existing.createdAt,
      },
    });
  },

  "GET /ai-service/health": () => {
    const health: AiServiceHealth = {
      status: "ok",
      service: "mediqueue-ai-summary-prototype (demo)",
      database: "sqlite",
      provider: {
        active: "demo",
        model: "demo-script",
        mode: "mock",
        note: "This is the demo mock. Run the ai-summary-prototype service for the real extractor.",
      },
      literature: { enabled: true, sources: ["Europe PMC", "PubMed"] },
      limits: {
        maxUploadBytes: 5 * 1024 * 1024,
        maxDocumentsPerPatient: 100,
        extractConcurrency: 2,
      },
    };

    return ok(health);
  },

  "GET /ai-service/patients/:id/summary": (request) => {
    const query = queryOf(request);
    const history = buildDemoHistory(query.id);

    return ok({ history });
  },

  "GET /ai-service/patients/:id/timeline": (request) => {
    const query = queryOf(request);
    const timeline = buildDemoTimeline(query.id);

    return ok({ timeline }, { total: timeline.length, pageSize: timeline.length });
  },

  "GET /ai-service/patients/:id/documents": (request) => {
    const query = queryOf(request);
    const db = readDb();

    const documents = db.records
      .filter((item) => item.patientId === query.id)
      .map((item) => ({
        id: item.id,
        patientId: item.patientId,
        filename: item.documentName ?? `${item.diagnosis}.pdf`,
        mime: "application/pdf",
        bytes: item.documentSize ?? 0,
        sha256: `demo-${item.id}`,
        note: null,
        source: "demo",
        externalId: null,
        uploadedAt: new Date(item.date).toISOString(),
        fileUrl: `/ai-service/documents/${item.id}/file`,
      }));

    return ok({ documents }, { total: documents.length, pageSize: documents.length });
  },

  "POST /ai-service/patients/:id/documents": (request) => {
    const query = queryOf(request);
    const body = bodyOf(request);
    const db = readDb();

    const patient = db.users.find((item) => item.id === query.id);

    if (!patient) {
      return fail("PATIENT_NOT_FOUND", "No such patient.", 404);
    }

    // The demo does not read the uploaded bytes — it records that a document
    // arrived and returns the demo history.
    const uploadedAt = new Date().toISOString();
    const id = `DOC-${db.counters.record + 1}`;

    writeDb((current) => ({
      ...current,
      records: [
        {
          ...current.records[0],
          id,
          patientId: query.id,
          date: format(new Date(), "yyyy-MM-dd"),
          visitType: "Follow-up",
          chiefComplaint: "Uploaded document",
          diagnosis: "Document under review",
          notes:
            typeof body.note === "string" && body.note
              ? body.note
              : "Uploaded through the AI summary service.",
          vitals: {
            bloodPressure: null,
            temperature: null,
            pulse: null,
            weight: null,
            spo2: null,
          },
          documentName: "upload.pdf",
          documentSize: 0,
          createdAt: uploadedAt,
          updatedAt: uploadedAt,
        },
        ...current.records,
      ],
      counters: { ...current.counters, record: current.counters.record + 1 },
    }));

    const history = buildDemoHistory(query.id);

    const result: AiUploadResult = {
      uploaded: [
        {
          document: {
            id,
            patientId: query.id,
            filename: "upload.pdf",
            mime: "application/pdf",
            bytes: 0,
            sha256: `demo-${id}`,
            note: typeof body.note === "string" ? body.note : null,
            source: "upload",
            externalId: null,
            uploadedAt,
            fileUrl: `/ai-service/documents/${id}/file`,
          },
          duplicate: false,
        },
      ],
      results: [
        {
          document: {
            id,
            patientId: query.id,
            filename: "upload.pdf",
            mime: "application/pdf",
            bytes: 0,
            sha256: `demo-${id}`,
            note: null,
            source: "upload",
            externalId: null,
            uploadedAt,
            fileUrl: `/ai-service/documents/${id}/file`,
          },
          summary: null,
          citations: [],
        },
      ],
      history,
    };

    return ok(result);
  },

  "GET /ai-service/patients/:id/citations": (request) => {
    const query = queryOf(request);
    const timeline = buildDemoTimeline(query.id);

    const citations = timeline.flatMap((entry) => entry.citations);

    return ok({ citations }, { total: citations.length, pageSize: citations.length });
  },

  "GET /ai-service/patients/:id/export": (request) => {
    const query = queryOf(request);
    return ok(buildDemoExport(query.id));
  },

  "POST /ai-service/patients/:id/sync": (request) => {
    const query = queryOf(request);
    return ok(buildDemoExport(query.id));
  },

  "GET /ai-service/documents/:id": (request) => {
    const query = queryOf(request);
    const db = readDb();

    const record = db.records.find((item) => item.id === query.id);

    if (!record) {
      return fail("DOCUMENT_NOT_FOUND", "No such document.", 404);
    }

    return ok({
      document: {
        id: record.id,
        patientId: record.patientId,
        filename: record.documentName ?? `${record.diagnosis}.pdf`,
        mime: "application/pdf",
        bytes: record.documentSize ?? 0,
        sha256: `demo-${record.id}`,
        note: null,
        source: "demo",
        externalId: null,
        uploadedAt: new Date(record.date).toISOString(),
        fileUrl: `/ai-service/documents/${record.id}/file`,
      },
      summary: null,
      citations: [],
      extraction: null,
    });
  },

  "POST /ai-service/summaries/:id/review": (request) => {
    const query = queryOf(request);
    const body = bodyOf(request);

    return ok({
      summary: {
        id: query.id,
        patientId: String(body.patientId ?? ""),
        generatedAt: new Date().toISOString(),
        simulated: true,
        headline: "Reviewed summary",
        summary: String(body.editedSummary ?? ""),
        keyFindings: [],
        currentMedications: [],
        allergies: [],
        conditions: [],
        recommendations: [],
        reviewed: body.needsReview !== true,
        editedSummary:
          typeof body.editedSummary === "string" ? body.editedSummary : null,
      },
      citations: [],
    });
  },

  "GET /ai-service/summaries/:id/citations": () => {
    const citations = DEMO_CITATIONS.map((citation, index) => ({
      ...citation,
      id: `CIT-${index}`,
      summaryId: "demo",
    }));

    return ok({ citations }, { total: citations.length, pageSize: citations.length });
  },
};
